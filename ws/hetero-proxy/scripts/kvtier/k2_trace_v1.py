# hetero-proxy KV tier K2 (2026-10-16): the users of the multi-user serving run - real multi-turn ShareGPT
# conversations (reassembled as in hf_reference_kv_v3.py), tokenized for Qwen2.5-32B-Instruct.
# Per user (one conversation): turn 0 = chat template of [default system prompt, first human message] with the
# generation prompt; turn k >= 1 = the tokens that follow the model's own reply k-1:
#     "<|im_end|>\n<|im_start|>user\n{human message k}<|im_end|>\n<|im_start|>assistant\n"
# (the replies are generated by the engine at serving time, so their content is not in the trace); reply length
# R_k = the dataset's gpt answer k in tokens, clipped to [16, 512] - the engine generates exactly R_k tokens, so
# every policy does the same work. A conversation is cut before the turn at which prompt + replies would pass
# --max_total tokens; conversations with fewer than 2 turns left are skipped. File order, deterministic.
# Usage: ~/.venvs/hetero-proxy-hf/bin/python k2_trace_v1.py --out <users.json> [--n 3000]
################################################################################
import argparse
import json
import os
import statistics
import sys

from transformers import AutoTokenizer

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "e2e"))
from hf_reference_kv_v3 import conversations  # noqa: E402
from qwen_tp_v1 import model_dir  # noqa: E402


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--n", type=int, default=3000)
    ap.add_argument("--max_total", type=int, default=8192 - 64)
    ap.add_argument("--r_min", type=int, default=16)
    ap.add_argument("--r_max", type=int, default=512)
    args = ap.parse_args()
    tok = AutoTokenizer.from_pretrained(model_dir())
    users = []
    for cid, turns in conversations():
        if len(turns) < 4 or any(t.get("from") != ("human" if j % 2 == 0 else "gpt") for j, t in enumerate(turns)):
            continue
        out, total = [], 0
        for k in range(0, len(turns) - 1, 2):
            msg, ans = turns[k]["value"], turns[k + 1]["value"]
            if k == 0:
                ids = tok.apply_chat_template([{"role": "user", "content": msg}], tokenize=True,
                                              add_generation_prompt=True)
            else:
                ids = tok("<|im_end|>\n<|im_start|>user\n" + msg + "<|im_end|>\n<|im_start|>assistant\n",
                          add_special_tokens=False).input_ids
            R = max(args.r_min, min(args.r_max, len(tok(ans, add_special_tokens=False).input_ids)))
            if total + len(ids) + R > args.max_total:
                break
            out.append(dict(ids=ids, R=R))
            total += len(ids) + R
        if len(out) >= 2:
            users.append(dict(conv_id=cid, turns=out, total=total))
            if len(users) == args.n:
                break
    nt = [len(u["turns"]) for u in users]
    tot = [u["total"] for u in users]
    T = [len(t["ids"]) for u in users for t in u["turns"][1:]]
    R = [t["R"] for u in users for t in u["turns"]]
    summ = dict(users=len(users), turns_mean=statistics.mean(nt), turns_median=statistics.median(nt),
                total_tokens_median=statistics.median(tot), total_tokens_p90=sorted(tot)[int(0.9 * len(tot))],
                new_turn_tokens_median=statistics.median(T), new_turn_tokens_p90=sorted(T)[int(0.9 * len(T))],
                reply_tokens_median=statistics.median(R), reply_tokens_mean=statistics.mean(R))
    print(json.dumps(summ, indent=1))
    with open(args.out, "w") as f:
        json.dump(dict(args=vars(args), summary=summ, users=users), f)


if __name__ == "__main__":
    main()
